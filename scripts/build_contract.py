"""Assemble a complete single-file native contract from the tested own sources."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = '# { "Depends": "py-genlayer:1jb45aa8ynh2a9c9xn3b7qqh8sm5q93hwfp7jqmwsfhh8jpz09h6" }\n\n'


def assembled():
    core = (ROOT / "accord_space/core.py").read_text()
    prompt = (ROOT / "accord_space/compiler_prompt.py").read_text()
    prompt = prompt.replace("from .core import PROTOCOL, _clauses, canonical\n", "")
    adapter = (ROOT / "contract_parts/adapter.py").read_text()
    return HEADER + "# GENERATED by python -m scripts.build_contract; edit assembly inputs.\n\n" + core + "\n\n" + prompt + "\n\n" + adapter


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "contracts/accord_space.py"
    content = assembled()
    if args.check:
        if not target.is_file() or target.read_text() != content:
            raise SystemExit("ERROR: canonical contract differs from assembly inputs")
        print("CONTRACT_ASSEMBLY_MATCH")
    else:
        target.write_text(content)
        print(target)
