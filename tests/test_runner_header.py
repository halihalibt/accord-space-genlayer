import json
import unittest

from scripts.build_contract import assembled
from scripts.check_runner_header import RUNNER, runner_config


class RunnerHeaderRegression(unittest.TestCase):
    def test_complete_assembled_header(self):
        self.assertEqual(runner_config(assembled()), {"Depends": RUNNER})

    def test_rejects_the_failed_deployment_header(self):
        header = '# { "Depends": "' + RUNNER + '" }\n'
        with self.assertRaises(json.JSONDecodeError):
            runner_config(header + '# v0.2.16\n# GENERATED by assembly\n\npass\n')

    def test_runtime_configuration_ends_before_documentation(self):
        source = assembled()
        self.assertEqual(source.splitlines()[1], "")
        self.assertIn("# GENERATED", source.splitlines()[2])


if __name__ == "__main__":
    unittest.main()
